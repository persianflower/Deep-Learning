axes[0].set_ylabel("Actual")

sns.heatmap(cm_deep_cnn,annot=True,fmt='d',cmap="Blues",ax=axes[0])
axes[0].set_title("Deep CNN model")
axes[0].set_xlabel("Predicted")
axes[0].set_ylabel("Actual")

plt.tight_layout()
plt.show()

